import assert from 'node:assert/strict'
import { pathToFileURL } from 'node:url'

const playwrightPath = process.env.SPM_PLAYWRIGHT_PATH
if (!playwrightPath) throw new Error('SPM_PLAYWRIGHT_PATH is required')
const { chromium } = await import(pathToFileURL(playwrightPath).href)
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, timezoneId: 'Asia/Tehran' })
const base = process.env.SPM_TEST_URL || 'http://127.0.0.1:5173'
const errors = []
page.on('pageerror', (error) => errors.push(error.message))

try {
  await page.goto(base)
  await page.locator('main').waitFor()
  await page.evaluate(async () => {
    const { db } = await import('/src/db/db.ts')
    await db.transaction('rw', db.tables, async () => { for (const table of db.tables) await table.clear() })
    const now = Date.now()
    await db.customers.add({ id: 'accounting-customer', name: 'مشتری حسابداری', mobile: '09120000000', createdAt: now, updatedAt: now })
    await db.projects.add({ id: 'accounting-project', customerId: 'accounting-customer', title: 'پروژه حسابداری', status: 'in_progress', pricingMode: 'itemized', initialEstimateAmount: 10000, executionStartDate: '2026-10-01', createdAt: now, updatedAt: now })
    await db.projectItems.add({ id: 'accounting-item', projectId: 'accounting-project', title: 'خدمت آزمون', unit: 'meter', quantity: 100, unitPrice: 100, totalPrice: 10000, pricingType: 'PER_METER', createdAt: now, updatedAt: now })
    await db.projectActivities.add({ id: 'accounting-activity', projectId: 'accounting-project', projectItemId: 'accounting-item', title: 'کارکرد آزمون', unit: 'meter', quantity: 40, date: '2026-10-20', createdAt: now, updatedAt: now })
    await db.projectChanges.add({ id: 'accounting-extra', projectId: 'accounting-project', title: 'کار اضافه آزمون', amount: 1000, date: '2026-10-21', createdAt: now, updatedAt: now })
    await db.invoices.add({ id: 'accounting-invoice', number: 'INV-TEST', customerId: 'accounting-customer', projectId: 'accounting-project', date: '2026-10-22', dueDate: '2026-10-24', status: 'issued', lines: [{ id: 'line', description: 'صورت‌حساب آزمون', quantity: 1, unitPrice: 3000, total: 3000 }], total: 3000, createdAt: now, updatedAt: now })
    await db.payments.add({ id: 'accounting-payment', customerId: 'accounting-customer', projectId: 'accounting-project', invoiceId: 'accounting-invoice', amount: 1000, date: '2026-10-23', method: 'card', createdAt: now, updatedAt: now })
    await db.expenses.add({ id: 'accounting-expense', projectId: 'accounting-project', title: 'هزینه آزمون', amount: 500, date: '2026-10-23', createdAt: now, updatedAt: now })
  })
  await page.goto(base + '/finance')
  await page.getByRole('heading', { name: 'حسابداری', exact: true }).waitFor()
  await page.getByText('برآورد، کارکرد و طلب قطعی از هم جدا هستند', { exact: true }).waitFor()
  const expected = new Map([
    ['برآورد فعلی', 11000], ['کارکرد خالص', 5000], ['کارکرد صورتحساب‌نشده', 2000], ['طلب قطعی', 3000],
    ['دریافتی', 1000], ['مانده قابل وصول', 2000], ['هزینه‌های ثبت‌شده', 500], ['سود کارکرد', 4500],
  ])
  for (const [label, value] of expected) {
    const card = page.locator('article').filter({ has: page.getByRole('heading', { name: label, exact: true }) })
    assert.equal(await card.count(), 1, `missing accounting card: ${label}`)
    assert.match(await card.innerText(), new RegExp(new Intl.NumberFormat('fa-IR').format(value)))
  }
  await page.getByLabel('مشتری').selectOption('accounting-customer')
  await page.getByText('۱ پروژه در این نما', { exact: true }).waitFor()
  const earnedCard = page.locator('article').filter({ has: page.getByRole('heading', { name: 'کارکرد خالص', exact: true }) })
  await earnedCard.getByRole('button').click()
  const earnedDetails = page.getByRole('region', { name: 'ریز کارکرد خالص' })
  await earnedDetails.waitFor()
  assert.match(await earnedDetails.innerText(), /پروژه حسابداری/)
  assert.match(await earnedDetails.innerText(), /کارکرد ۴٬۰۰۰ تومان \+ کار اضافه ۱٬۰۰۰ تومان/)
  await earnedDetails.getByRole('button', { name: 'بستن' }).click()
  const overdueCard = page.locator('article').filter({ has: page.getByRole('heading', { name: 'سررسید گذشته (۱)', exact: true }) })
  await overdueCard.getByRole('button').click()
  const overdueDetails = page.getByRole('region', { name: 'ریز فاکتورهای سررسید گذشته' })
  await overdueDetails.waitFor()
  assert.match(await overdueDetails.innerText(), /INV-TEST/)
  assert.match(await overdueDetails.innerText(), /۲٬۰۰۰ تومان/)
  await overdueDetails.getByRole('button', { name: 'ثبت دریافت مرتبط' }).click()
  const paymentEditor = page.locator('#accounting-payment-editor')
  await paymentEditor.waitFor()
  assert.equal(await paymentEditor.getByLabel('مشتری پرداخت').inputValue(), 'accounting-customer')
  assert.equal(await paymentEditor.getByLabel('پروژه پرداخت').inputValue(), 'accounting-project')
  assert.equal(await paymentEditor.getByLabel('فاکتور پرداخت').inputValue(), 'accounting-invoice')
  await paymentEditor.getByRole('button', { name: 'انصراف' }).click()
  const unbilledCard = page.locator('article').filter({ has: page.getByRole('heading', { name: 'کارکرد صورتحساب‌نشده', exact: true }) })
  await unbilledCard.getByRole('button').click()
  const unbilledDetails = page.getByRole('region', { name: 'ریز کارکرد صورتحساب‌نشده' })
  await unbilledDetails.getByRole('button', { name: 'ساخت فاکتور باقی‌مانده' }).click()
  const invoiceEditor = page.locator('#accounting-document-editor')
  await invoiceEditor.waitFor()
  assert.equal(await invoiceEditor.getByLabel('پروژه').inputValue(), 'accounting-project')
  await invoiceEditor.getByRole('button', { name: 'پیشنهاد مبلغ باقی‌مانده پروژه' }).click()
  await invoiceEditor.getByText(/فقط ۲٬۰۰۰ تومان پیشنهاد شد/).waitFor()
  assert.match(await invoiceEditor.innerText(), /جمع سند: ۲٬۰۰۰ تومان/)
  await invoiceEditor.getByRole('button', { name: 'انصراف' }).click()
  await page.goto(base + '/customers/accounting-customer')
  const customerAccount = page.getByRole('region', { name: 'حساب مشتری' })
  await customerAccount.waitFor()
  assert.match(await customerAccount.innerText(), /برآورد فعلی/)
  assert.match(await customerAccount.innerText(), /طلب قطعی\s*۳٬۰۰۰ تومان/)
  assert.match(await customerAccount.innerText(), /مانده قابل وصول\s*۲٬۰۰۰ تومان/)
  await customerAccount.getByRole('link', { name: /باز کردن ریز حسابداری/ }).click()
  await page.getByRole('heading', { name: 'حسابداری', exact: true }).waitFor()
  assert.equal(await page.getByLabel('مشتری').inputValue(), 'accounting-customer')
  assert.equal(await page.getByRole('region', { name: 'ریز مانده قابل وصول' }).count(), 1)
  await page.goto(base + '/projects/accounting-project')
  const projectAccount = page.getByRole('region', { name: 'حساب پروژه' })
  await projectAccount.waitFor()
  await projectAccount.getByText('کارکرد خالص', { exact: true }).waitFor()
  assert.match(await projectAccount.innerText(), /کارکرد خالص\s*۵٬۰۰۰ تومان/)
  assert.match(await projectAccount.innerText(), /بدهکار: ۲٬۰۰۰ تومان/)
  assert.equal(errors.length, 0, errors.join('\n'))
  console.log('Accounting dashboard, customer account, project account and filtered drill-downs share one financial source of truth.')
} finally {
  await browser.close()
}
